def transform_intellectual_style(text, mode="article", persona=None):
    clean_input = text.strip()
    if not clean_input:
        return ""

    cfg = load_config()
    active_mode = cfg.get("active_mode", "authentic")
    # إذا لم يُحدد المسار بالطلب، نستخدم المسار المحفوظ في الإعدادات
    active_persona = persona or cfg.get("active_persona", "author_1")

    # 1. إذا طلب المستخدم صراحة الذكاء الاصطناعي السحابي (Groq)
    if active_mode == "groq" and cfg.get("groq_api_key"):
        groq_res = call_groq_api(cfg["groq_api_key"], clean_input, mode=mode, model=cfg.get("groq_model", "qwen/qwen3.8-27b"), persona=active_persona)
        if groq_res:
            return groq_res

    # 2. إذا طلب المستخدم صراحة سيرفر كولاب السحابي
    if active_mode == "cloud" and cfg.get("colab_url"):
        cloud_res = call_colab_gradio(cfg["colab_url"], clean_input, mode=mode, persona=active_persona)
        if cloud_res:
            return cloud_res

    # 3. إذا طلب المستخدم صراحة سيرفر أولاما المحلي
    if active_mode == "local" and cfg.get("ollama_url"):
        ollama_res = call_local_ollama(cfg["ollama_url"], cfg.get("ollama_model", "academic_editor"), clean_input, mode=mode, persona=active_persona)
        if ollama_res:
            return ollama_res

    # 4. التوليد البشري الأصيل للمسارات المدمجة (Local Authentic Human Corpora)
    if active_persona == "author_2":
        return generate_academic_thesis_style(clean_input, mode=mode)
    elif active_persona == "author_3":
        return generate_human_authorship_style(clean_input, mode=mode)
    else:
        # Default: author_1 (المحاكي الفكري البلاغي 100%)
        return generate_authentic_corpus_style(clean_input, mode=mode)
