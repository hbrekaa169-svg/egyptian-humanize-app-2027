def extract_core_entity_and_facts(text):
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    first_clause = lines[0].split(".")[0].split("،")[0].strip() if lines else "هذه القضية"
    for prefix in ["تكتسب", "تعد", "يمثل", "إن", "يعتبر", "تعتبر", "دراسة", "موضوع", "بحث", "أهمية", "يهدف", "بشأن", "حول"]:
        if first_clause.startswith(prefix):
            first_clause = first_clause[len(prefix):].strip()

    citations = re.findall(r"\[(.*?)\]|\((.*?)\)", text)
    cit_list = []
    for c in citations:
        val = c[0] if c[0] else c[1]
        if any(yr in val for yr in ["198", "199", "200", "201", "202"]):
            cit_list.append(f"[{val}]")
    cit_str = " ؛ ".join(cit_list[:2]) if cit_list else ""

    numbers = re.findall(r"(\d+(?:\.\d+)?\s*(?:%|مليار|مليون|ألف|طن|دولار|جنيه))", text)
    num_str = " و ".join(numbers[:3]) if numbers else ""
    return first_clause, cit_str, num_str

