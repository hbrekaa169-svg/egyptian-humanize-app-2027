def apply_orthographic_rules(text, style="author_1"):
    """
    تطبيق القواعد الإملائية والترقيمية الدقيقة وفق المسار المختار:
    - author_1: ياء منقوطة صارمة، فواصل متباعدة بمسافتين، نقطتا توقف تأملي (..)، شرطات اعتراضية (—)
    - author_2: ياء منقوطة منضبطة، فواصل منقوطة نظامية، تنسيق هرمي مبحثي أكاديمي
    """
    t = text
    # Dotted ya rules
    t = re.sub(r"\bفي\b", "فى", t)
    t = re.sub(r"\bإلي\b", "إلى", t)
    t = re.sub(r"\bعلي\b", "على", t)
    t = re.sub(r"\bحتي\b", "حتى", t)
    
    if style in ("author_1", "authentic"):
        # Double-spaced comma: [كلمة] [،] [كلمة]
        t = re.sub(r"\s*([،؛])\s*", r" \1 ", t)
        # Contemplative double-dot pause
        t = re.sub(r"\s*(\.\.\.)\s*", r".. ", t)
        t = re.sub(r"\s*(\.\.)\s*", r".. ", t)
        # Spaced end punctuations
        t = re.sub(r"\s*([\.!\?])\s*(?=\n|$)", r" \1", t)
    elif style == "author_3":
        # Humanized Scholarly (AI-Skills standard: Natural cadence, single space after punctuation)
        t = re.sub(r"\s*([،,])\s*", r"\1 ", t)
        t = re.sub(r"\s*([؛;])\s*", r"\1 ", t)
        t = re.sub(r"\s*([\.:])\s*", r"\1 ", t)
        t = re.sub(r" +", " ", t)
    else:
        # Standard formal academic punctuation
        t = re.sub(r"\s*([،,])\s*", r"\1 ", t)
        t = re.sub(r"\s*([؛;])\s*", r"\1 ", t)
        t = re.sub(r"\s*([\.:])\s*", r"\1 ", t)

    return t

