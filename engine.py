def call_groq_api(api_key, text, mode="article", model="qwen/qwen3.8-27b", persona="author_1"):
    """الاتصال السحابي عبر Groq API"""
    if not api_key:
        return None
    
    url = "https://api.groq.com/openai/v1/chat/completions"
    persona_labels = {
        "author_1": "المقال الفكري التحليلي البلاغي في الاقتصاد السياسي والتنمية",
        "author_2": "المبحث الأكاديمي المحكّم ورسائل الماجستير والسياسات العامة",
        "author_3": "استوديو البصمة البشرية والتحرير الجنائي ومكافحة التوليد الآلي (Human Authorship)"
    }
    persona_label = persona_labels.get(persona, "المقال الفكري التحليلي البلاغي")
    user_instruction = (
        f"المطلوب: أعد صياغة وتحليل النص التالي بأسلوب {persona_label} في نمط {mode}.\n\n"
        f"النص المراد صياغته:\n{text}"
    )

    candidate_models = [model or "qwen/qwen3.8-27b", "qwen/qwen3.8-27b", "allam-2-7b", "openai/gpt-oss-120b"]
    seen = set()
    models_to_try = [m for m in candidate_models if m and not (m in seen or seen.add(m))]

    for m in models_to_try:
        payload = json.dumps({
            "model": m,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT_INTELLECTUAL},
                {"role": "user", "content": user_instruction}
            ],
            "temperature": 0.65,
            "max_tokens": 2048
        }).encode("utf-8")

        req = urllib.request.Request(
            url,
            data=payload,
            headers={
                "Authorization": f"Bearer {api_key.strip()}",
                "Content-Type": "application/json",
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
            },
            method="POST"
        )

        try:
            with urllib.request.urlopen(req, timeout=30) as res:
                if res.status == 200:
                    data = json.loads(res.read().decode("utf-8"))
                    choices = data.get("choices", [])
                    if choices:
                        content = choices[0].get("message", {}).get("content", "")
                        if content:
                            return apply_orthographic_rules(content.strip(), style=persona)
        except Exception:
            continue
    return None

def call_colab_gradio(colab_url, text, mode="article", persona="author_1"):
    """الاتصال بسيرفر كولاب السحابي عبر Gradio API"""
    if not colab_url:
        return None
    url = colab_url.strip().rstrip("/")
    if not url.endswith("/api/predict"):
        api_endpoint = f"{url}/api/predict"
    else:
        api_endpoint = url

    payload = json.dumps({"data": [text, mode]}).encode("utf-8")
    req = urllib.request.Request(api_endpoint, data=payload, headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=35) as res:
            if res.status == 200:
                data = json.loads(res.read().decode("utf-8"))
                if "data" in data and len(data["data"]) > 0:
                    return apply_orthographic_rules(data["data"][0], style=persona)
    except Exception:
        pass
    return None

